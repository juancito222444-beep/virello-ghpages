const {chromium}=require('playwright');
const path=require('node:path');
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{}),args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 const page=await browser.newPage({viewport:{width:1512,height:1050}});const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const base=process.env.ANTO_TEST_URL||'http://127.0.0.1:8765';const created=await page.request.post(base+'/api/projects',{data:{name:'SINTÉTICO · E2E herramientas'}});if(!created.ok())throw Error('No se pudo crear proyecto sintético');const project=await created.json();await page.goto(base);await page.getByLabel('Proyecto activo').selectOption(project.id);await page.waitForSelector('canvas');await page.waitForTimeout(1000);
 await page.getByRole('button',{name:'VERA Análisis'}).click();await page.getByRole('heading',{name:'VERA',exact:false}).waitFor();
 await page.getByRole('button',{name:'Acercar',exact:true}).click();await page.getByRole('button',{name:'Restablecer vista',exact:true}).click();
 await page.getByRole('button',{name:'Datos',exact:true}).click();
 await page.locator('input[type=file]').setInputFiles(path.resolve(__dirname,'../../examples/ventas_sinteticas.csv'));
 await page.getByText('duplicados conservados').waitFor();
 await page.getByLabel('Objetivo',{exact:true}).fill('SINTÉTICO: ingresos por producto');
 await page.getByLabel('Agrupar por',{exact:true}).selectOption('producto');
 await page.getByLabel('Calcular ingresos').check();
 await page.getByLabel('Cantidad',{exact:true}).selectOption('cantidad');
 await page.getByLabel('Precio',{exact:true}).selectOption('precio');
 await page.getByRole('button',{name:'Preparar plan de cálculo'}).click();
 await page.getByRole('button',{name:'Aprobar y ejecutar'}).first().click();
 await page.locator('.status.success').first().waitFor({timeout:30000});
 if(!await page.getByText('100',{exact:true}).count())throw Error('No se mostró total=100');
 await page.getByRole('button',{name:'Entregables',exact:true}).click();
 const downloadPromise=page.waitForEvent('download');await page.getByRole('link').filter({hasText:'entrega.zip'}).first().click();const download=await downloadPromise;
 if(download.suggestedFilename()!=='entrega.zip')throw Error('Descarga incorrecta');
 await page.getByRole('button',{name:'Oficina',exact:true}).click();await page.waitForSelector('canvas');
 const activity=await page.locator('.activity-entries').innerText();if(!activity.includes('Completado'))throw Error('La oficina no recibió eventos');
 await page.setViewportSize({width:390,height:844});await page.waitForTimeout(500);
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Desbordamiento móvil');
 if(errors.length)throw Error(errors.join('\n'));
 console.log('PASS: oficina, selección, cámara, datos, aprobación, total 100, ZIP real, eventos y móvil.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
